-- Туман кампуса: карту открывает группа, ногами.
--
-- Карта уже умеет рисовать туман и «опорные точки», каждая из которых
-- раздвигает исследованную область на радиус подложки (55 м). До сих пор
-- этот список был записан в данных и не менялся. Теперь в него попадают
-- места, где участники действительно побывали, и открытый кусок виден всем.
--
-- Здесь нет account_id, и это не упущение. Механике нужно знать, какие
-- клетки открыты, а не кто где был; хранить историю перемещений шестидесяти
-- подростков ради тумана на карте — цена, которой эта игра не стоит.
-- Ограничение частоты живёт в памяти процесса, как и счётчик попыток входа.
--
-- Клетка — координата, снапнутая к сетке в 0,0004° (около 44 м на широте
-- Хайнаня). Хранится целыми: с плавающей точкой равенство ключей зависело бы
-- от округления, а это первичный ключ.
CREATE TABLE v4_campus_cells (
    season_id INTEGER NOT NULL,
    cell_lon INTEGER NOT NULL,
    cell_lat INTEGER NOT NULL,
    opened_at TEXT NOT NULL DEFAULT (
        strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
    ),
    visits INTEGER NOT NULL DEFAULT 1 CHECK (visits > 0),
    PRIMARY KEY (season_id, cell_lon, cell_lat),
    FOREIGN KEY (season_id) REFERENCES v4_seasons(id) ON DELETE RESTRICT
);

-- Выборка всегда идёт по сезону целиком: следующая поездка начинается в
-- темноте, и чужие клетки в неё не переносятся.
CREATE INDEX v4_campus_cells_season_idx ON v4_campus_cells(season_id, opened_at);
